SELECT * FROM TB_VENDA;
SELECT * FROM TB_PRODUTO_QUANTIDADE;
SELECT v.ID, v.CODIGO, c.NOME AS CLIENTE, p.NOME AS PRODUTO,
       i.QUANTIDADE, i.VALOR_TOTAL, v.STATUS_VENDA
FROM TB_VENDA v JOIN TB_CLIENTE c ON c.ID = v.ID_CLIENTE_FK
JOIN TB_PRODUTO_QUANTIDADE i ON i.ID_VENDA_FK = v.ID
JOIN TB_PRODUTO p ON p.ID = i.PRODUTO_ID;
